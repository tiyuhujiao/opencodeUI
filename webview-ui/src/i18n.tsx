const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<UiLanguage>(readInitialLanguage)
  const setLanguage = useCallback((next: UiLanguage) => {
    setLanguageState(next)
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next)
    } catch {
      // Persistence is best-effort in restricted webviews.
    }
  }, [])
  const t = useCallback((source: string, values?: TranslationValues) => {
    const template = language === 'zh-CN' ? (ZH_CN[source] ?? source) : source
    return interpolate(template, values)
  }, [language])

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext)
  if (!value) {
    throw new Error('useI18n must be used inside I18nProvider')
  }
  return value
}

export function translate(language: UiLanguage, source: string, values?: TranslationValues): string {
  return interpolate(language === 'zh-CN' ? (ZH_CN[source] ?? source) : source, values)
}

function readInitialLanguage(): UiLanguage {
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (stored === 'zh-CN' || stored === 'en') {
      return stored
    }
  } catch {
    // Fall through to the browser language.
  }
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

function interpolate(template: string, values?: TranslationValues): string {
  if (!values) {
    return template
  }
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key: string) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  ))
}
